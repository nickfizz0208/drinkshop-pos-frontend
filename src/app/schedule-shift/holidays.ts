/** 週六、週日或國定假日。 */
export function isOffDay(date: string): boolean {
  const [y, m, d] = date.split('-').map(Number);
  const w = new Date(y, m - 1, d).getDay();
  return w === 0 || w === 6 || date in HOLIDAYS;
}
